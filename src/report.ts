/** Session → markdown report with findings, evidence excerpts and artifact links. */
import { readFile } from "node:fs/promises";
import type { Session, ToolResult } from "./contracts.js";
import { redact } from "./safety.js";

const SEV_ICON: Record<string, string> = { high: "🔴", warn: "🟠", info: "🔵" };

export async function renderReport(session: Session): Promise<string> {
  const runs: ToolResult[] = [];
  for (const r of session.runs) {
    try {
      runs.push(JSON.parse(await readFile(r.file, "utf8")) as ToolResult);
    } catch {
      /* skip */
    }
  }
  return renderReportFromRuns(session, runs);
}

/** Pure renderer, testable. */
export function renderReportFromRuns(session: Session, runs: ToolResult[]): string {
  const t = session.target;
  const lines: string[] = [];
  lines.push(`# Debug Anything session ${session.id}`);
  lines.push("");
  lines.push(`- **Target:** ${t.kind} \`${t.id}\`${t.pid ? ` (pid ${t.pid}` + (t.comm ? `, ${t.comm}` : "") + ")" : ""}${t.runtime ? ` — runtime ${t.runtime}` : ""}`);
  lines.push(`- **Host:** ${t.host} (${session.platform})`);
  lines.push(`- **Created:** ${session.created_at}${session.detached_at ? ` · **Detached:** ${session.detached_at}` : ""}`);
  lines.push(`- **Runs:** ${runs.length} · **Artifacts dir:** \`${session.dir}\``);
  lines.push("");

  const all = runs.flatMap((r) => r.findings.map((f) => ({ run: r, f })));
  const order = { high: 0, warn: 1, info: 2 } as const;
  all.sort((a, b) => order[a.f.severity] - order[b.f.severity]);
  lines.push("## Findings");
  lines.push("");
  if (all.length === 0) lines.push("_No findings recorded._");
  for (const { run, f } of all) {
    lines.push(`- ${SEV_ICON[f.severity]} **${f.severity.toUpperCase()}** ${redact(f.summary)}  `);
    lines.push(`  _${f.confidence}_ · ${run.run_id ?? run.tool} · evidence: ${f.evidence_ids.map((e) => `\`${run.run_id ?? run.tool}/${e}\``).join(", ")}`);
    if (f.detail) lines.push(`  ${redact(f.detail)}`);
  }
  lines.push("");

  lines.push("## Runs");
  lines.push("");
  for (const r of runs) {
    lines.push(`### ${r.run_id ?? r.tool} — ${r.ok ? "ok" : "FAILED"} (${r.duration_ms} ms)`);
    lines.push("");
    if (r.error) lines.push(`**Error:** ${redact(r.error)}\n`);
    if (r.evidence.length) {
      lines.push("| id | kind | summary | source |");
      lines.push("|---|---|---|---|");
      for (const e of r.evidence) {
        const src = e.artifact ? `\`${shortPath(e.artifact)}\`${e.lines ? ` L${e.lines[0]}–${e.lines[1]}` : ""}` : "";
        lines.push(`| ${e.id} | ${e.kind} | ${escapeCell(redact(e.summary))} | ${src} |`);
      }
      lines.push("");
    }
    if (r.limitations.length) {
      lines.push("**Limitations:**");
      for (const l of r.limitations) lines.push(`- ${redact(l)}`);
      lines.push("");
    }
    if (r.artifacts.length) {
      lines.push("**Artifacts:**");
      for (const a of r.artifacts) lines.push(`- \`${a.path}\` (${a.kind}, ${a.bytes} bytes${a.truncated ? ", truncated" : ""})`);
      lines.push("");
    }
    if (r.suggested_next.length) lines.push(`_Suggested next:_ ${r.suggested_next.join(", ")}\n`);
  }
  lines.push("---");
  lines.push("_Generated by DebugAnything (Debug Anything). Every finding above cites evidence ids; raw artifacts are unredacted on disk._");
  return lines.join("\n") + "\n";
}

function shortPath(p: string): string {
  const i = p.lastIndexOf("/");
  return i >= 0 ? p.slice(i + 1) : p;
}

function escapeCell(s: string): string {
  return s.replace(/\|/g, "\\|").replace(/\n/g, " ");
}
